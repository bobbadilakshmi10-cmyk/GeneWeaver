
# Import the prepare_data function from the fasta_pipeline.py file inside the member1 folder
from member1.fasta_pipeline import prepare_data

# Call the prepare_data function to read the sample FASTA file and split DNA sequences into chunks of 5 characters
records = prepare_data("data/sample.fasta", chunk_size=5)

# Check whether at least one DNA chunk is generated; otherwise, display the error message
assert len(records) > 0, "No DNA records found!"

# Loop through each DNA record (chunk) one by one
for record in records:

    # Check whether the current DNA record contains an ID
    assert "id" in record, "DNA ID is missing"

    # Check whether the current DNA record contains a DNA sequence
    assert "sequence" in record, "DNA sequence is missing"

    # Check whether the DNA sequence contains no more than 5 characters
    assert len(record["sequence"]) <= 5, "Chunk is too long"

# Display this success message if all the above tests pass
print("All pipeline tests passed!")

# Display the total number of DNA chunks generated by the pipeline
print("Total DNA chunks:", len(records))